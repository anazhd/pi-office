// Pure, platform-simulatable logic for the Pi Office setup CLI (scripts/setup.mjs). No side effects here: the CLI
// turns these plans into file writes and commands. Unit tested on any OS via scripts/setup.test.mjs.
//
// Supported service managers (all per-user, never admin, never touching ~/.pi):
//   linux  systemd user unit  ~/.config/systemd/user/pi-office.service   (systemctl --user)
//   darwin launchd agent       ~/Library/LaunchAgents/local.pi-office.plist (launchctl bootstrap gui/<uid>)
//   win32  Startup-folder launcher (no Task Scheduler/admin): a minimised "Pi Office" console window per logon
// Anything else (or Linux without a systemd user session, e.g. WSL1/containers): run "npm start" in the
// foreground or under your own supervisor.
import { posix, win32 } from 'node:path'
import { ConfigError, RUNTIME_ENV_KEYS, loadConfig } from '../server/config.ts'
import { deskStatePath, expandUserPath, piAgentDir, piSessionsLocation } from '../server/paths.ts'

export const MIN_NODE = [24, 12, 0]
export const SYSTEMD_UNIT = 'pi-office.service'
export const LAUNCHD_LABEL = 'local.pi-office'
export const WINDOWS_TITLE = 'Pi Office'
/** A string only the development fixture contains; a production dist/ must never include it. */
export const MOCK_MARKER = 'qwen/qwen3.5-coder'
/** Env keys whose values are paths: expanded like Pi does and required to be absolute in a service. */
export const PATH_KEYS = ['PI_OFFICE_SESSIONS_DIR', 'PI_CODING_AGENT_SESSION_DIR', 'PI_CODING_AGENT_DIR', 'PI_OFFICE_STATE_FILE', 'XDG_STATE_HOME']

export class SetupError extends Error {}

/** null when the running Node is new enough, else an actionable message. */
export function nodeVersionProblem(version) {
  const parts = String(version).replace(/^v/, '').split('.').map((n) => Number.parseInt(n, 10) || 0)
  for (let i = 0; i < 3; i++) {
    if (parts[i] > MIN_NODE[i]) return null
    if (parts[i] < MIN_NODE[i]) {
      return 'Node ' + version + ' is too old: Pi Office needs Node >= ' + MIN_NODE.join('.') +
        ' (it runs TypeScript directly). Install a current LTS from https://nodejs.org or your version manager, then retry.'
    }
  }
  return null
}

/** Keep a stable PATH symlink to this exact Node binary; avoid fnm's disposable shell links. */
export function serviceNodePath({ execPath, pathEnv = '', platform, realpath = (p) => p }) {
  const path = pathApi(platform)
  const canonical = (p) => {
    try {
      const resolved = realpath(p)
      return platform === 'win32' ? resolved.toLowerCase() : resolved
    } catch { return null }
  }
  const target = canonical(execPath)
  const transient = (p) => /fnm_multishells|[\\\\/]_npx[\\\\/]|^[\\\\/]tmp[\\\\/]/i.test(p)
  for (const dir of pathEnv.split(platform === 'win32' ? ';' : ':').filter(Boolean)) {
    if (!path.isAbsolute(dir) || transient(dir)) continue
    const candidate = path.join(dir, platform === 'win32' ? 'node.exe' : 'node')
    if (target && canonical(candidate) === target) return candidate
  }
  return transient(execPath) ? (realpath(execPath) || execPath) : execPath
}

/** Extract the installed executable for doctor diagnostics; only definitions generated by this CLI are parsed. */
export function installedNodePath(manager, text) {
  if (!text) return null
  if (manager === 'systemd') {
    const match = String(text).match(/^ExecStart=(?:"((?:\\.|[^"])*)"|(\S+))/m)
    if (!match) return null
    return (match[1] ?? match[2]).replace(/\\(.)/g, '$1').replace(/%%/g, '%').replace(/\$\$/g, '$')
  }
  if (manager === 'launchd') {
    const match = String(text).match(/<key>ProgramArguments<\/key>\s*<array>\s*<string>([\s\S]*?)<\/string>/)
    return match ? unxml(match[1]) : null
  }
  const match = String(text).match(/^"([^"]+)"\s+"[^"]+server[\\/]index\.ts"/m)
  return match ? match[1].replace(/%%/g, '%') : null
}

function pathApi(platform) {
  return platform === 'win32' ? win32 : posix
}

function assertPlainValue(key, value, platform) {
  if (/[\u0000-\u001f\u007f]/.test(value)) throw new SetupError(key + ' contains a control character or newline')
  if (platform === 'win32' && value.includes('"')) throw new SetupError(key + ' cannot contain a double quote on Windows')
}

/**
 * Environment for the service: the current process env seeds NEW installations only. Existing service settings
 * are authoritative on upgrades; explicit --env overrides / --unset are the only changes. Path values are expanded and must be
 * absolute (a service has no meaningful cwd or shell). The result must pass the server's own config validation.
 */
export function serviceEnv({ existing = {}, isNewInstall = Object.keys(existing).length === 0, env = {}, set = {}, unset = [], allowRemoteBind = false, platform, home }) {
  const out = {}
  for (const [k, v] of Object.entries(existing)) if (!k.startsWith('EXPO_PUBLIC_')) out[k] = v
  if (isNewInstall) {
    for (const key of RUNTIME_ENV_KEYS) {
      const value = env[key]
      if (typeof value === 'string' && value.trim()) out[key] = value.trim()
    }
  }
  for (const [k, v] of Object.entries(set)) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new SetupError('invalid variable name: ' + k)
    if (k.startsWith('EXPO_PUBLIC_')) throw new SetupError(k + ' is a build-time variable; it has no effect on the server')
    out[k] = v
  }
  for (const k of unset) delete out[k]
  if (allowRemoteBind) out.PI_OFFICE_ALLOW_REMOTE_BIND = '1'
  out.HOST ??= '127.0.0.1'
  out.PORT ??= '6702'

  const path = pathApi(platform)
  for (const key of PATH_KEYS) {
    if (out[key] === undefined) continue
    const expanded = expandUserPath(out[key], { platform, home })
    if (!path.isAbsolute(expanded)) {
      throw new SetupError(key + '=' + out[key] + ' must be an absolute path (or start with ~) for a background service')
    }
    out[key] = path.normalize(expanded)
  }
  for (const [k, v] of Object.entries(out)) assertPlainValue(k, v, platform)
  try {
    loadConfig(out)
  } catch (error) {
    if (error instanceof ConfigError) {
      throw new SetupError(error.message + (/ALLOW_REMOTE_BIND/.test(error.message) ? ' Pass --allow-remote-bind to confirm.' : ''))
    }
    throw error
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
}

// ------------------------------------------------------------------ systemd

/** Quote one systemd word: backslash escapes inside double quotes, and %-specifiers neutralised. */
export function systemdQuote(value, { exec = false } = {}) {
  let v = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%')
  if (exec) v = v.replace(/\$/g, '$$$$')
  return '"' + v + '"'
}

export function renderSystemdUnit({ node, repo, env }) {
  const lines = [
    '# Written by pi-office setup (scripts/setup.mjs). Re-run it to change settings; existing Environment= lines are kept.',
    '[Unit]',
    'Description=Pi Office',
    'After=network-online.target',
    '',
    '[Service]',
    'WorkingDirectory=' + repo.replace(/%/g, '%%'),
    ...Object.entries(env).map(([k, v]) => 'Environment=' + systemdQuote(k + '=' + v)),
    'ExecStart=' + systemdQuote(node, { exec: true }) + ' ' + systemdQuote(posix.join(repo, 'server', 'index.ts'), { exec: true }),
    'Restart=always',
    'RestartSec=3',
    'TimeoutStopSec=10',
    'NoNewPrivileges=true',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ]
  return lines.join('\n')
}

/** Environment= assignments of an existing unit (quoted or bare, several per line), specifiers unescaped. */
export function parseSystemdEnv(text) {
  const env = {}
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.trim()
    if (!line.startsWith('Environment=')) continue
    const rest = line.slice('Environment='.length)
    const words = []
    let i = 0
    while (i < rest.length) {
      while (rest[i] === ' ' || rest[i] === '\t') i++
      if (i >= rest.length) break
      let word = ''
      if (rest[i] === '"' || rest[i] === "'") {
        const quote = rest[i++]
        while (i < rest.length && rest[i] !== quote) {
          if (rest[i] === '\\' && i + 1 < rest.length) i++
          word += rest[i++]
        }
        i++
      } else {
        while (i < rest.length && rest[i] !== ' ' && rest[i] !== '\t') word += rest[i++]
      }
      words.push(word.replace(/%%/g, '%'))
    }
    for (const word of words) {
      const eq = word.indexOf('=')
      if (eq > 0) env[word.slice(0, eq)] = word.slice(eq + 1)
    }
  }
  return env
}

// ------------------------------------------------------------------ launchd

const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const unxml = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&')

export function renderLaunchdPlist({ node, repo, env, logDir }) {
  const str = (s) => '    <string>' + xml(s) + '</string>'
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<!-- Written by pi-office setup (scripts/setup.mjs). Re-run it to change settings; EnvironmentVariables are kept. -->',
    '<plist version="1.0">',
    '<dict>',
    '  <key>Label</key>',
    '  <string>' + LAUNCHD_LABEL + '</string>',
    '  <key>ProgramArguments</key>',
    '  <array>',
    str(node),
    str(posix.join(repo, 'server', 'index.ts')),
    '  </array>',
    '  <key>WorkingDirectory</key>',
    '  <string>' + xml(repo) + '</string>',
    '  <key>EnvironmentVariables</key>',
    '  <dict>',
    ...Object.entries(env).flatMap(([k, v]) => ['    <key>' + xml(k) + '</key>', '    <string>' + xml(v) + '</string>']),
    '  </dict>',
    '  <key>RunAtLoad</key>',
    '  <true/>',
    '  <key>KeepAlive</key>',
    '  <true/>',
    '  <key>ThrottleInterval</key>',
    '  <integer>5</integer>',
    '  <key>StandardOutPath</key>',
    '  <string>' + xml(posix.join(logDir, 'pi-office.log')) + '</string>',
    '  <key>StandardErrorPath</key>',
    '  <string>' + xml(posix.join(logDir, 'pi-office.err.log')) + '</string>',
    '</dict>',
    '</plist>',
    '',
  ].join('\n')
}

export function parseLaunchdEnv(text) {
  const env = {}
  const block = String(text).match(/<key>EnvironmentVariables<\/key>\s*<dict>([\s\S]*?)<\/dict>/)
  if (!block) return env
  const pair = /<key>([\s\S]*?)<\/key>\s*<string>([\s\S]*?)<\/string>/g
  for (let m = pair.exec(block[1]); m; m = pair.exec(block[1])) env[unxml(m[1])] = unxml(m[2])
  return env
}

// ------------------------------------------------------------------ Windows

/** In a .cmd file, %% is a literal percent inside set "K=V"; everything else between the quotes is literal. */
const cmdValue = (s) => s.replace(/%/g, '%%')

export function renderWindowsRunner({ node, repo, env, logFile }) {
  return [
    '@echo off',
    'rem Written by pi-office setup (scripts/setup.mjs). Re-run it to change settings; set lines are kept.',
    'setlocal DisableDelayedExpansion',
    'title ' + WINDOWS_TITLE,
    ...Object.entries(env).map(([k, v]) => 'set "' + k + '=' + cmdValue(v) + '"'),
    'cd /d "' + cmdValue(repo) + '"',
    ':run',
    '"' + cmdValue(node) + '" "' + cmdValue(win32.join(repo, 'server', 'index.ts')) + '" >> "' + cmdValue(logFile) + '" 2>&1',
    'rem Restart after a crash, like Restart=always. Close this window to stop Pi Office.',
    'timeout /t 3 /nobreak >nul',
    'goto run',
    '',
  ].join('\r\n')
}

export function renderWindowsStartup({ runner }) {
  // The outer batch parser sees the path between doubled quotes as unquoted: escape its metacharacters
  // once here. The inner cmd /s /c then receives the intact, quoted path.
  const outerPath = cmdValue(runner).replace(/[&|<>^()]/g, '^$&')
  return [
    '@echo off',
    'setlocal DisableDelayedExpansion',
    'rem Starts Pi Office minimised at logon. Remove with: node scripts/setup.mjs uninstall-service',
    'start "' + WINDOWS_TITLE + '" /min cmd.exe /d /s /c ""' + outerPath + '""',
    '',
  ].join('\r\n')
}

export function parseWindowsEnv(text) {
  const env = {}
  for (const line of String(text).split(/\r?\n/)) {
    const m = line.match(/^set "([A-Za-z_][A-Za-z0-9_]*)=(.*)"\s*$/)
    if (m) env[m[1]] = m[2].replace(/%%/g, '%')
  }
  return env
}

// ------------------------------------------------------------------ plans

/**
 * Where each platform's service definition lives. env supplies XDG_CONFIG_HOME / APPDATA / LOCALAPPDATA.
 */
export function serviceLocations({ platform, home, env = {} }) {
  if (platform === 'linux') {
    const config = env.XDG_CONFIG_HOME?.trim() || posix.join(home, '.config')
    return { manager: 'systemd', file: posix.join(config, 'systemd', 'user', SYSTEMD_UNIT) }
  }
  if (platform === 'darwin') {
    return {
      manager: 'launchd',
      file: posix.join(home, 'Library', 'LaunchAgents', LAUNCHD_LABEL + '.plist'),
      logDir: posix.join(home, 'Library', 'Logs', 'pi-office'),
    }
  }
  if (platform === 'win32') {
    const appData = env.APPDATA?.trim() || win32.join(home, 'AppData', 'Roaming')
    const local = env.LOCALAPPDATA?.trim() || win32.join(home, 'AppData', 'Local')
    const dir = win32.join(local, 'pi-office')
    return {
      manager: 'startup-folder',
      file: win32.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup', 'pi-office.cmd'),
      runner: win32.join(dir, 'pi-office-run.cmd'),
      logFile: win32.join(dir, 'pi-office.log'),
      dir,
    }
  }
  return null
}

export function parseExistingEnv(manager, text) {
  if (!text) return {}
  if (manager === 'systemd') return parseSystemdEnv(text)
  if (manager === 'launchd') return parseLaunchdEnv(text)
  return parseWindowsEnv(text)
}

/**
 * Everything install-service would do, as data: { manager, files: [{path, content}], dirs, commands: [{argv,
 * allowFailure?}], notes }. existingText is the current service definition (or its runner on Windows), if any.
 */
export function installPlan({ platform, home, uid, node, repo, env: processEnv = {}, existingText = null, set = {}, unset = [], allowRemoteBind = false }) {
  const where = serviceLocations({ platform, home, env: processEnv })
  if (!where) {
    throw new SetupError(
      'No built-in user service for ' + platform + '. Run "npm start" in the foreground, or under your own supervisor ' +
        '(the server needs only Node, this checkout and its environment variables).',
    )
  }
  for (const [key, value] of Object.entries({ home, node, repo, file: where.file, runner: where.runner, logDir: where.logDir, logFile: where.logFile })) {
    if (value !== undefined) assertPlainValue(key, value, platform)
  }
  const existing = parseExistingEnv(where.manager, existingText)
  const env = serviceEnv({ existing, isNewInstall: existingText === null, env: processEnv, set, unset, allowRemoteBind, platform, home })
  const url = 'http://' + (env.HOST.includes(':') ? '[' + env.HOST + ']' : env.HOST) + ':' + env.PORT + '/'
  const notes = []
  if (/Cellar|node-versions|[\\/]v\d+\.\d+/i.test(node)) {
    notes.push('Node is pinned to ' + node + '. If your version manager removes it, rerun setup after upgrading Node.')
  }

  if (where.manager === 'systemd') {
    notes.push('User services stop at logout unless lingering is enabled: loginctl enable-linger "$USER" (may need your admin).')
    notes.push('Logs: journalctl --user -u ' + SYSTEMD_UNIT + ' -f')
    return {
      manager: where.manager,
      url,
      env,
      dirs: [posix.dirname(where.file)],
      files: [{ path: where.file, content: renderSystemdUnit({ node, repo, env }) }],
      commands: [
        { argv: ['systemctl', '--user', 'daemon-reload'] },
        { argv: ['systemctl', '--user', 'enable', SYSTEMD_UNIT] },
        { argv: ['systemctl', '--user', 'restart', SYSTEMD_UNIT] },
      ],
      notes,
    }
  }
  if (where.manager === 'launchd') {
    const domain = 'gui/' + uid
    notes.push('Logs: ' + posix.join(where.logDir, 'pi-office.log') + ' and pi-office.err.log')
    return {
      manager: where.manager,
      url,
      env,
      dirs: [posix.dirname(where.file), where.logDir],
      files: [{ path: where.file, content: renderLaunchdPlist({ node, repo, env, logDir: where.logDir }) }],
      commands: [
        { argv: ['launchctl', 'bootout', domain + '/' + LAUNCHD_LABEL], allowFailure: true },
        { argv: ['launchctl', 'bootstrap', domain, where.file], retry: { attempts: 10, delayMs: 500, statuses: [5] } },
        { argv: ['launchctl', 'kickstart', '-k', domain + '/' + LAUNCHD_LABEL] },
      ],
      notes,
    }
  }
  notes.push('Starts at each logon as a minimised "' + WINDOWS_TITLE + '" window; close that window to stop it until the next logon.')
  notes.push('An already running copy is not replaced: close its window first, or the new one exits with "address in use".')
  notes.push('Logs: ' + where.logFile)
  return {
    manager: where.manager,
    url,
    env,
    dirs: [where.dir, win32.dirname(where.file)],
    files: [
      { path: where.runner, content: renderWindowsRunner({ node, repo, env, logFile: where.logFile }) },
      { path: where.file, content: renderWindowsStartup({ runner: where.runner }) },
    ],
    commands: [{ argv: ['cmd.exe', '/d', '/s', '/c', '""' + where.file + '""'], detached: true, windowsVerbatimArguments: true }],
    notes,
  }
}

export function uninstallPlan({ platform, home, uid, env = {} }) {
  const where = serviceLocations({ platform, home, env })
  if (!where) throw new SetupError('No built-in user service for ' + platform + '; nothing to remove.')
  if (where.manager === 'systemd') {
    return {
      manager: where.manager,
      commands: [{ argv: ['systemctl', '--user', 'disable', '--now', SYSTEMD_UNIT], allowFailure: true }],
      remove: [where.file],
      after: [{ argv: ['systemctl', '--user', 'daemon-reload'], allowFailure: true }],
      notes: ['Desk state is kept; delete it yourself if you no longer want it.'],
    }
  }
  if (where.manager === 'launchd') {
    return {
      manager: where.manager,
      commands: [{ argv: ['launchctl', 'bootout', 'gui/' + uid + '/' + LAUNCHD_LABEL], allowFailure: true }],
      remove: [where.file],
      after: [],
      notes: ['Logs in ' + where.logDir + ' and desk state are kept.'],
    }
  }
  return {
    manager: where.manager,
    commands: [],
    remove: [where.file, where.runner],
    after: [],
    notes: ['Close the "' + WINDOWS_TITLE + '" window if it is still running. Logs and desk state are kept.'],
  }
}

/** The data locations a service with this env would use (for doctor / dry-run output). */
export function dataLocations({ env, platform, home, exists, readText }) {
  const options = { env, platform, home, exists, readText }
  const sessions = piSessionsLocation(options)
  return { sessions: sessions.dir, sessionsSource: sessions.source, models: piAgentDir(options), deskState: deskStatePath(options) }
}
